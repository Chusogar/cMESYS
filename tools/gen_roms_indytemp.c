// gen_roms_indytemp.c - writes main/drivers/arcades/indytemp/rom_data.c (the
// ROMs in the firmware's flash, tiles packed to 4bpp) from the unzipped
// indytemp + atarisy1 sets, with the same loader as the desktop build.
// Built and run by tools/regen.sh indytemp.
#include <stdio.h>
#include <stdlib.h>
#include "indytemp_roms.h"

static void bytes(FILE *o, const char *name, const uint8_t *d, int n)
{
    fprintf(o, "const uint8_t %s[0x%x] = {\n", name, n);
    for (int i = 0; i < n; i++) fprintf(o, "%u,%s", d[i], (i % 32 == 31) ? "\n" : "");
    fprintf(o, "};\n\n");
}

int main(int argc, char **argv)
{
    if (argc < 4) { fprintf(stderr, "usage: %s <indytemp dir> <atarisy1 dir> <out.c>\n", argv[0]); return 1; }
    indy_roms r;
    char err[512];
    if (!indy_load_roms(argv[1], argv[2], &r, err, sizeof err)) { fprintf(stderr, "%s\n", err); return 1; }
    FILE *o = fopen(argv[3], "w");
    if (!o) { perror(argv[3]); return 1; }
    fprintf(o, "/* Generated by tools/gen_roms.c from indytemp + atarisy1 - do not edit */\n");
    fprintf(o, "#include \"rom_data.h\"\n\n");
    bytes(o, "indy_main_rom", r.main, INDY_MAIN_IMAGE);
    bytes(o, "indy_sound_rom", r.sound, 0xc000);
    bytes(o, "indy_char_rom", r.chars, 0x2000);
    bytes(o, "indy_prom_data", r.proms, 0x400);
    for (int b = 1; b < INDY_GFX_BANKS; b++) {
        if (!r.tiles[b]) continue;
        fprintf(o, "static const uint32_t tiles_bank%d[0x%x] = {\n", b, INDY_TILES_PER_BANK * 8);
        for (int i = 0; i < INDY_TILES_PER_BANK * 8; i++)
            fprintf(o, "0x%x,%s", r.tiles[b][i], (i % 16 == 15) ? "\n" : "");
        fprintf(o, "};\n\n");
    }
    fprintf(o, "void indy_rom_data(indy_roms *r)\n{\n");
    fprintf(o, "    r->main = indy_main_rom;\n    r->sound = indy_sound_rom;\n");
    fprintf(o, "    r->chars = indy_char_rom;\n    r->proms = indy_prom_data;\n");
    for (int b = 1; b < INDY_GFX_BANKS; b++)
        if (r.tiles[b]) fprintf(o, "    r->tiles[%d] = tiles_bank%d;\n", b, b);
        else fprintf(o, "    r->tiles[%d] = NULL;\n", b);
    fprintf(o, "}\n");
    fclose(o);
    return 0;
}
