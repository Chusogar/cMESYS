#!/usr/bin/env python3
"""Pack the Puzzle Bobble (Taito B System, MAME set "pbobble") ROMs into
main/drivers/arcades/pbobble/rom_data.c (const arrays -> ESP32 flash).
Run by tools/regen.sh pbobble.

  pb-ic18.ic18 / pb-ic2.ic2   68000 program, even / odd bytes (2 x 256 KB)
  pb-ic27.ic27                Z80 sound program (128 KB, 4 banks of 16 KB)
  pb-ic14.ic14 / pb-ic9.ic9   TC0180VCU graphics, planes 0-1 / 2-3 (2 x 512 KB)
  pb-ic15.ic15                YM2610B ADPCM-A samples (1 MB)

The graphics are stored decoded as 8x8 characters, 4 bits per pixel, 4 bytes
per row (left pixel in the high nibble), 32 bytes per character: the 16x16
tiles are characters 4n (top left), 4n+1 (top right), 4n+2 (bottom left) and
4n+3 (bottom right). Same size as the original ROMs.
"""
import os, sys, zlib

ROMS = {  # name: (size, crc32)
    "pb-ic18.ic18": (0x40000, 0x5de14f49),
    "pb-ic2.ic2": (0x40000, 0x2abe07d1),
    "pb-ic27.ic27": (0x20000, 0x26efa4c4),
    "pb-ic14.ic14": (0x80000, 0x55f90ea4),
    "pb-ic9.ic9": (0x80000, 0x3253aac9),
    "pb-ic15.ic15": (0x100000, 0x0840cbc4),
}

def load(d, name):
    p = os.path.join(d, name)
    if not os.path.exists(p):
        sys.exit("missing ROM: " + p)
    data = open(p, "rb").read()
    size, crc = ROMS[name]
    if len(data) != size:
        sys.exit("%s: size %d, expected %d" % (name, len(data), size))
    if zlib.crc32(data) & 0xffffffff != crc:
        print("warning: %s has CRC %08x, expected %08x" % (name, zlib.crc32(data) & 0xffffffff, crc))
    return data

def main():
    d, out = sys.argv[1], sys.argv[2]
    even, odd = load(d, "pb-ic18.ic18"), load(d, "pb-ic2.ic2")
    prog = bytearray(0x80000)
    prog[0::2] = even
    prog[1::2] = odd
    snd = load(d, "pb-ic27.ic27")
    lo, hi = load(d, "pb-ic14.ic14"), load(d, "pb-ic9.ic9")
    # char c, row y: plane bytes lo[c*16+y*2], lo[c*16+y*2+1], hi[...], hi[...+1]
    # pixel x = p0<<3 | p1<<2 | p2<<1 | p3 (bit 7-x of each plane byte)
    spread = [0] * 256
    for b in range(256):
        v = 0
        for x in range(8):
            if b & (0x80 >> x):
                v |= 1 << (4 * (7 - x))
        spread[b] = v
    gfx = bytearray(0x100000)
    for c in range(0x8000):
        for y in range(8):
            o = c * 16 + y * 2
            v = (spread[lo[o]] << 3) | (spread[lo[o + 1]] << 2) | (spread[hi[o]] << 1) | spread[hi[o + 1]]
            gfx[c * 32 + y * 4:c * 32 + y * 4 + 4] = v.to_bytes(4, "big")
    adpcm = load(d, "pb-ic15.ic15")

    with open(out, "w") as f:
        f.write("// Auto-generated by tools/gen_roms_pbobble.py - Puzzle Bobble ROM data\n")
        f.write('#include "rom_data.h"\n\n')
        for name, data in (("pb_prog_rom", prog), ("pb_snd_rom", snd), ("pb_gfx_rom", gfx),
                           ("pb_adpcma_rom", adpcm)):
            f.write("const uint8_t %s[%d] __attribute__((aligned(4))) = {\n" % (name, len(data)))
            for i in range(0, len(data), 32):
                f.write("".join("0x%02x," % b for b in data[i:i + 32]) + "\n")
            f.write("};\n\n")
    print("OK ->", out)

main()
