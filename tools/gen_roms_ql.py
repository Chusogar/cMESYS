#!/usr/bin/env python3
"""Pack the Sinclair QL ROMs (MAME set "ql", JS ROM) and a microdrive
cartridge into main/drivers/computers/ql/rom_data.c (const arrays -> ESP32
flash). Run by tools/regen.sh ql.

  ql.js 0000.ic33, ql.js 8000.ic34   system ROM, JS (0000-BFFF)
  ipc8049.ic24                       8749 IPC program
  *.mdv (first one in roms/ql)       QLAY microdrive cartridge (174930 bytes),
                                     the one F1 / the MDV button mounts in mdv1
"""
import glob, os, sys, zlib

ROMS = {  # name: (size, crc32)
    "ql.js 0000.ic33": (0x8000, 0x1bbad3b8),
    "ql.js 8000.ic34": (0x4000, 0xc970800e),
    "ipc8049.ic24": (0x800, 0x6a0d1f20),
}
MDV_BYTES = 255 * 686


def load(d, name):
    p = os.path.join(d, name)
    if not os.path.exists(p):
        sys.exit("missing ROM: " + p)
    data = open(p, "rb").read()
    size, crc = ROMS[name]
    if len(data) != size:
        sys.exit("%s: size %d, expected %d" % (name, len(data), size))
    if zlib.crc32(data) & 0xffffffff != crc:
        print("warning: %s has CRC %08x, expected %08x" % (name, zlib.crc32(data) & 0xffffffff, crc))
    return data


def array(out, decl, data):
    out.append("%s = {" % decl)
    for i in range(0, len(data), 24):
        out.append("    " + ",".join("0x%02x" % b for b in data[i:i + 24]) + ",")
    out.append("};")


def main():
    if len(sys.argv) < 3:
        sys.exit("usage: gen_roms_ql.py roms/ql out/rom_data.c [cartridge.mdv]")
    d, outp = sys.argv[1], sys.argv[2]
    rom = load(d, "ql.js 0000.ic33") + load(d, "ql.js 8000.ic34")
    ipc = load(d, "ipc8049.ic24")
    mdvs = [sys.argv[3]] if len(sys.argv) > 3 else sorted(glob.glob(os.path.join(d, "*.mdv")))
    out = ["// Generated by tools/gen_roms_ql.py - do not edit", '#include "rom_data.h"', ""]
    array(out, "const uint8_t ql_rom[0xc000]", rom)
    array(out, "const uint8_t ql_ipc_rom[0x800]", ipc)
    if mdvs:
        mdv = open(mdvs[0], "rb").read()
        if len(mdv) != MDV_BYTES:
            sys.exit("%s: %d bytes, a QLAY .mdv has %d" % (mdvs[0], len(mdv), MDV_BYTES))
        name = os.path.splitext(os.path.basename(mdvs[0]))[0]
        array(out, "static const uint8_t mdv[%d]" % MDV_BYTES, mdv)
        out.append("const uint8_t *const ql_mdv_image = mdv;")
        out.append('const char ql_mdv_name[] = "%s";' % name.replace('"', "'"))
        print("cartridge: %s (medium '%s')" % (mdvs[0], mdv[14:24].decode("latin-1").rstrip()))
    else:
        print("no .mdv in %s: the build has no cartridge" % d)
        out.append("const uint8_t *const ql_mdv_image = 0;")
        out.append('const char ql_mdv_name[] = "";')
    open(outp, "w").write("\n".join(out) + "\n")


main()
