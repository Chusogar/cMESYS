#!/usr/bin/env python3
"""Makes the header that puts a game's hottest 68000 opcode handlers in RAM
on the RP2040 (main/ports/rp2040-pizero): the handlers listed in the game's
ESP32 linker fragment (<game>.lf, measured per game), as declarations with
the SDK's RAM section, force-included when Musashi's opcode files are built
(Musashi itself is not changed).

  pico_hot.py <game>.lf out.h [max_handlers]
"""
import re, sys
lf, out = sys.argv[1], sys.argv[2]
limit = int(sys.argv[3]) if len(sys.argv) > 3 else 10000
names = []
for line in open(lf):
    m = re.match(r"\s*m68kop(?:ac|dm|nz):(m68k_op_\w+)\s*\(noflash\)", line)
    if m and m.group(1) not in names:
        names.append(m.group(1))
names = names[:limit]
with open(out, "w") as f:
    f.write("/* Generated by tools/pico_hot.py from %s - do not edit */\n" % lf.split("/")[-1])
    for n in names:
        f.write('void %s(void) __attribute__((section(".time_critical.%s")));\n' % (n, n))
print("%s: %d hot 68000 handlers in RAM" % (out.split("/")[-1], len(names)))
