// gen_roms.c - Host tool: loads the Track & Field ROM set exactly like
// zxm/trackfld.c, decodes graphics with the same code and writes common/rom_data.c.
//
//   cc -O2 -o gen_roms tools/gen_roms.c && ./gen_roms roms common/rom_data.c
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>

static uint8_t mainrom[0x10000];
static uint8_t audiorom[0x4000];
static uint8_t vlmrom[0x4000];
static uint8_t gfx1[0x8000];
static uint8_t gfx2[0x6000];
static uint8_t prom[0x220];
static uint8_t chr_pix[768][8][8];
static uint8_t spr_pix[256][16][16];

static int load_rom(const char *dir, const char *name, uint8_t *dst, size_t cap, size_t off, size_t len)
{
    char path[1024];
    snprintf(path, sizeof path, "%s/%s", dir, name);
    FILE *f = fopen(path, "rb");
    if (!f) { fprintf(stderr, "[ROM] missing %s\n", path); return -1; }
    fseek(f, 0, SEEK_END); long sz = ftell(f); fseek(f, 0, SEEK_SET);
    if (sz != (long)len || off + len > cap || fread(dst + off, 1, len, f) != len) {
        fprintf(stderr, "[ROM] error %s\n", path); fclose(f); return -1;
    }
    fclose(f);
    fprintf(stderr, "[ROM] %s\n", path);
    return 0;
}

static inline uint8_t gfx_bit(const uint8_t *src, int bitoff) { return (src[bitoff >> 3] >> (7 - (bitoff & 7))) & 1; }

static void decode_chars(void)
{
    for (int code = 0; code < 768; ++code) {
        int base = code * 32;
        for (int y = 0; y < 8; ++y) {
            int row = base + y * 4;
            for (int x = 0; x < 8; ++x) {
                uint8_t v = gfx2[row + (x >> 1)];
                chr_pix[code][y][x] = (x & 1) ? (v & 0x0f) : (v >> 4);
            }
        }
    }
}

static void decode_sprites(void)
{
    static const int planeoffs[4] = { 0, 4, 256 * 64 * 8 + 0, 256 * 64 * 8 + 4 };
    static const int xoffs[16] = { 0,1,2,3, 8*8+0,8*8+1,8*8+2,8*8+3, 16*8+0,16*8+1,16*8+2,16*8+3, 24*8+0,24*8+1,24*8+2,24*8+3 };
    static const int yoffs[16] = { 0*8,1*8,2*8,3*8,4*8,5*8,6*8,7*8, 32*8,33*8,34*8,35*8,36*8,37*8,38*8,39*8 };
    for (int code = 0; code < 256; ++code) {
        int base = code * 64 * 8;
        for (int y = 0; y < 16; ++y)
            for (int x = 0; x < 16; ++x) {
                uint8_t pen = 0;
                for (int plane = 0; plane < 4; ++plane)
                    pen |= gfx_bit(gfx1, base + planeoffs[plane] + yoffs[y] + xoffs[x]) << plane;
                spr_pix[code][y][x] = pen;
            }
    }
}

static void emit(FILE *o, const char *name, const uint8_t *d, size_t n)
{
    // 16-byte align: clang -O2 may vectorize PROM/gfx reads with movdqa.
    fprintf(o, "const uint8_t %s[%zu] __attribute__((aligned(16))) = {\n", name, n);
    for (size_t i = 0; i < n; i++)
        fprintf(o, "%s0x%02x,%s", (i % 16) ? "" : "  ", d[i], (i % 16 == 15) ? "\n" : "");
    fprintf(o, "};\n\n");
}

int main(int argc, char **argv)
{
    if (argc < 3) { fprintf(stderr, "usage: %s <romdir> <out.c>\n", argv[0]); return 1; }
    const char *dir = argv[1];
    memset(mainrom, 0, sizeof mainrom);
    int e = 0;
    e |= load_rom(dir, "a01_e01.bin", mainrom, sizeof mainrom, 0x6000, 0x2000);
    e |= load_rom(dir, "a02_e02.bin", mainrom, sizeof mainrom, 0x8000, 0x2000);
    e |= load_rom(dir, "a03_k03.bin", mainrom, sizeof mainrom, 0xa000, 0x2000);
    e |= load_rom(dir, "a04_e04.bin", mainrom, sizeof mainrom, 0xc000, 0x2000);
    e |= load_rom(dir, "a05_e05.bin", mainrom, sizeof mainrom, 0xe000, 0x2000);
    e |= load_rom(dir, "c2_d13.bin", audiorom, sizeof audiorom, 0x0000, 0x2000);
    e |= load_rom(dir, "c9_d15.bin", vlmrom, sizeof vlmrom, 0x0000, 0x2000);
    const char *g1[] = { "c11_d06.bin", "c12_d07.bin", "c13_d08.bin", "c14_d09.bin" };
    for (int i = 0; i < 4; ++i) e |= load_rom(dir, g1[i], gfx1, sizeof gfx1, i * 0x2000, 0x2000);
    const char *g2[] = { "h16_e12.bin", "h15_e11.bin", "h14_e10.bin" };
    for (int i = 0; i < 3; ++i) e |= load_rom(dir, g2[i], gfx2, sizeof gfx2, i * 0x2000, 0x2000);
    e |= load_rom(dir, "361b16.f1", prom, sizeof prom, 0x000, 0x020);
    e |= load_rom(dir, "361b17.b16", prom, sizeof prom, 0x020, 0x100);
    e |= load_rom(dir, "361b18.e15", prom, sizeof prom, 0x120, 0x100);
    if (e) return 1;
    decode_chars();
    decode_sprites();

    FILE *o = fopen(argv[2], "w");
    if (!o) { perror(argv[2]); return 1; }
    fprintf(o, "// Auto-generated by tools/gen_roms.c - Track & Field ROM data\n#include \"rom_data.h\"\n\n");
    emit(o, "tf_main_rom", mainrom + 0x6000, 0xA000);
    emit(o, "tf_audio_rom", audiorom, sizeof audiorom);
    emit(o, "tf_vlm_rom", vlmrom, sizeof vlmrom);
    emit(o, "tf_prom", prom, sizeof prom);
    emit(o, "tf_chr_pix", &chr_pix[0][0][0], sizeof chr_pix);
    emit(o, "tf_spr_pix", &spr_pix[0][0][0], sizeof spr_pix);
    fclose(o);
    fprintf(stderr, "OK -> %s\n", argv[2]);
    return 0;
}
