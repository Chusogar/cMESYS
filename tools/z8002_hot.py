#!/usr/bin/env python3
"""Makes main/cpu/z8002/z8002_hot.h: declarations that put the Z8002's helper
functions and its busiest opcode handlers in RAM (IRAM on the ESP32, the
.time_critical sections on the RP2040). The whole core (~100 KB) does not fit.

  z8002_hot.py main/cpu/z8002/z8002_ops.inc hot.txt main/cpu/z8002/z8002_hot.h

hot.txt: handler names, one a line, the busiest first (measured on the host
with gprof call counts, Pole Position 1 and 2, attract mode and a race).
"""
import re, sys
ops, hotf, out = sys.argv[1:4]
src = open(ops).read()
hot = [l.strip() for l in open(hotf) if l.strip()]
sigs = {}
for m in re.finditer(r"^static (?!inline)([\w\s\*]+?) (\w+)\(([^)]*)\)\s*(?:;|\{|\n\{)", src, flags=re.M):
    sigs.setdefault(m.group(2), (m.group(1), m.group(3) or "void"))
names = [n for n in sigs if not re.match(r"Z[0-9A-F]{2}_", n)] + [n for n in hot if n in sigs]
with open(out, "w") as f:
    f.write("/* Generated by tools/z8002_hot.py - do not edit */\n")
    f.write("#ifndef Z8002_HOT_H\n#define Z8002_HOT_H\n#include <stdint.h>\n")
    f.write("#if defined(ESP_PLATFORM)\n#include \"esp_attr.h\"\n#define Z8_RAM IRAM_ATTR\n")
    f.write("#elif defined(PICO_ON_DEVICE) && PICO_ON_DEVICE\n#define Z8_RAM __attribute__((section(\".time_critical.z8002\")))\n")
    f.write("#else\n#define Z8_RAM\n#endif\n")
    for n in names:
        r, a = sigs[n]
        f.write("static %s %s(%s) Z8_RAM;\n" % (r, n, a))
    f.write("#endif\n")
print("%s: %d functions in RAM (%d handlers)" % (out, len(names), len([n for n in names if n in hot])))
