// gen_roms_atarisy1.c - writes main/drivers/arcades/<game>/rom_data.c (the
// ROMs in the firmware's flash, tiles packed to 4bpp) of an Atari System 1
// game (indytemp, roadrunn) from its unzipped set + atarisy1 (BIOS), with the
// same loader as the desktop build. Built and run by tools/regen.sh <game>.
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "atarisy1_roms.h"

static void bytes(FILE *o, const char *name, const uint8_t *d, int n)
{
    fprintf(o, "const uint8_t %s[0x%x] = {\n", name, n);
    for (int i = 0; i < n; i++) fprintf(o, "%u,%s", d[i], (i % 32 == 31) ? "\n" : "");
    fprintf(o, "};\n\n");
}

int main(int argc, char **argv)
{
    if (argc < 5) { fprintf(stderr, "usage: %s indytemp|roadrunn <game dir> <atarisy1 dir> <out.c>\n", argv[0]); return 1; }
    as1_game game = strcmp(argv[1], "roadrunn") == 0 ? AS1_ROADRUNN : AS1_INDYTEMP;
    as1_roms r;
    char err[512];
    if (!as1_load_roms(game, argv[2], argv[3], &r, err, sizeof err)) { fprintf(stderr, "%s\n", err); return 1; }
    FILE *o = fopen(argv[4], "w");
    if (!o) { perror(argv[4]); return 1; }
    fprintf(o, "/* Generated by tools/gen_roms_atarisy1.c from %s + atarisy1 - do not edit */\n", argv[1]);
    fprintf(o, "#include \"rom_data.h\"\n\n");
    bytes(o, "as1_main_rom", r.main, AS1_MAIN_IMAGE);
    bytes(o, "as1_sound_rom", r.sound, 0xc000);
    bytes(o, "as1_char_rom", r.chars, 0x2000);
    bytes(o, "as1_prom_data", r.proms, 0x400);
    for (int b = 1; b < AS1_GFX_BANKS; b++) {
        if (!r.tiles[b]) continue;
        fprintf(o, "static const uint32_t tiles_bank%d[0x%x] = {\n", b, AS1_TILES_PER_BANK * 8);
        for (int i = 0; i < AS1_TILES_PER_BANK * 8; i++)
            fprintf(o, "0x%x,%s", r.tiles[b][i], (i % 16 == 15) ? "\n" : "");
        fprintf(o, "};\n\n");
    }
    fprintf(o, "void as1_rom_data(as1_roms *r)\n{\n");
    fprintf(o, "    r->game = %s;\n", game == AS1_ROADRUNN ? "AS1_ROADRUNN" : "AS1_INDYTEMP");
    fprintf(o, "    r->main = as1_main_rom;\n    r->sound = as1_sound_rom;\n");
    fprintf(o, "    r->chars = as1_char_rom;\n    r->proms = as1_prom_data;\n");
    for (int b = 1; b < AS1_GFX_BANKS; b++)
        if (r.tiles[b]) fprintf(o, "    r->tiles[%d] = tiles_bank%d;\n", b, b);
        else fprintf(o, "    r->tiles[%d] = NULL;\n", b);
    fprintf(o, "}\n");
    fclose(o);
    return 0;
}
