#!/usr/bin/env python3
"""Pack the Gauntlet (Atari, 1985, MAME set "gauntlet", rev 14) ROMs into
main/drivers/arcades/gauntlet/rom_data.c (const arrays -> ESP32 flash).
Run by tools/regen.sh gauntlet.

  136037-1307.9a / 1308.9b    68010 $00000-$0FFFF (even / odd, halves swapped)
  136037-205.10a / 206.10b    68010 $38000-$3FFFF (SLAPSTIC 104, 4 banks)
  136037-1409.7a / 1410.7b    68010 $40000-$4FFFF (even / odd, halves swapped)
  136037-120.16r / 119.16s    6502 $4000-$7FFF / $8000-$FFFF
  136037-104.6p               alphanumerics, 2bpp
  136037-111..118             playfield / motion object tiles, 4 planes, inverted

The tiles are stored decoded: 8 rows of 32 bits per 8x8 tile, pixel x in
bits 4x..4x+3 (same size as the ROMs). The PROMs are not needed.
"""
import os, sys, zlib

ROMS = {  # name: (size, crc32)
    "136037-1307.9a": (0x8000, 0x46fe8743),
    "136037-1308.9b": (0x8000, 0x276e15c4),
    "136037-205.10a": (0x4000, 0x6d99ed51),
    "136037-206.10b": (0x4000, 0x545ead91),
    "136037-1409.7a": (0x8000, 0x6fb8419c),
    "136037-1410.7b": (0x8000, 0x931bd2a0),
    "136037-120.16r": (0x4000, 0x6ee7f3cc),
    "136037-119.16s": (0x8000, 0xfa19861f),
    "136037-104.6p": (0x4000, 0x6c276a1d),
    "136037-111.1a": (0x8000, 0x91700f33),
    "136037-112.1b": (0x8000, 0x869330be),
    "136037-113.1l": (0x8000, 0xd497d0a8),
    "136037-114.1mn": (0x8000, 0x29ef9882),
    "136037-115.2a": (0x8000, 0x9510b898),
    "136037-116.2b": (0x8000, 0x11e0ac5b),
    "136037-117.2l": (0x8000, 0x29a5db41),
    "136037-118.2mn": (0x8000, 0x8bf3b263),
}
TILES = ["136037-111.1a", "136037-112.1b", "136037-113.1l", "136037-114.1mn",
         "136037-115.2a", "136037-116.2b", "136037-117.2l", "136037-118.2mn"]


def load(d, name):
    p = os.path.join(d, name)
    if not os.path.exists(p):
        sys.exit("missing ROM: " + p)
    data = open(p, "rb").read()
    size, crc = ROMS[name]
    if len(data) != size:
        sys.exit("%s: size %d, expected %d" % (name, len(data), size))
    if zlib.crc32(data) & 0xffffffff != crc:
        print("warning: %s has CRC %08x, expected %08x" % (name, zlib.crc32(data) & 0xffffffff, crc))
    return data


def put16(prog, base, data, odd):
    for i, b in enumerate(data):
        prog[base + 2 * i + odd] = b


def main():
    d, out = sys.argv[1], sys.argv[2]
    prog = bytearray(0x80000)
    for base, ev, od in ((0x00000, "136037-1307.9a", "136037-1308.9b"),
                         (0x40000, "136037-1409.7a", "136037-1410.7b")):
        for odd, name in ((0, ev), (1, od)):
            r = load(d, name)
            put16(prog, base + 0x8000, r[:0x4000], odd)     # ROM_LOAD at +$8000
            put16(prog, base, r[0x4000:], odd)              # ROM_CONTINUE at +0
    put16(prog, 0x38000, load(d, "136037-205.10a"), 0)
    put16(prog, 0x38000, load(d, "136037-206.10b"), 1)
    snd = load(d, "136037-120.16r") + load(d, "136037-119.16s")
    chars = load(d, "136037-104.6p")
    spr = bytes(0xff ^ b for b in b"".join(load(d, n) for n in TILES))   # ROMREGION_INVERT
    tiles = []
    for at in range(0x2000 * 8):
        row = 0
        for k in range(4):           # plane at (3 - k) / 4 of the region -> pen bit 3 - k
            b = spr[(3 - k) * 0x10000 + at]
            for x in range(8):
                row |= ((b >> (7 - x)) & 1) << (4 * x + 3 - k)
        tiles.append(row)

    with open(out, "w") as f:
        f.write("// Auto-generated by tools/gen_roms_gauntlet.py - Gauntlet ROM data\n")
        f.write('#include "rom_data.h"\n\n')
        for name, data in (("gt_main_rom", prog), ("gt_sound_rom", snd), ("gt_char_rom", chars)):
            f.write("const uint8_t %s[%d] __attribute__((aligned(4))) = {\n" % (name, len(data)))
            for i in range(0, len(data), 32):
                f.write("".join("0x%02x," % b for b in data[i:i + 32]) + "\n")
            f.write("};\n\n")
        f.write("const uint32_t gt_tile_rom[%d] = {\n" % len(tiles))
        for i in range(0, len(tiles), 8):
            f.write("".join("0x%08x," % v for v in tiles[i:i + 8]) + "\n")
        f.write("};\n\n")
        f.write("void gt_rom_data(gt_roms *r)\n{\n"
                "    r->main = gt_main_rom;\n    r->sound = gt_sound_rom;\n"
                "    r->chars = gt_char_rom;\n    r->tiles = gt_tile_rom;\n}\n")
    print("OK ->", out)


main()
