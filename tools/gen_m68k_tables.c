// gen_m68k_tables.c - builds Musashi's opcode tables on the host and writes
// them as const data (ESP32 flash) so the 256 KB jump table and 192 KB cycle
// tables do not need RAM.
//
// Built with the game's Musashi set-up (its m68k_game_conf.h on the include
// path) and run by tools/regen.sh <game>; CYC_CPU = 0 for a 68000, 1 for a 68010.
//
// Output: m68k_handlers[] (function pointers, in m68kops.c table order),
//         m68k_op_index_flash[65536] (uint16 handler index), m68k_op_cycles[65536].
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <ctype.h>

// Pull the real table + builder from Musashi (handlers become declarations only).
#include "m68kops.c"

// Cycle table written: 1 = 68010 (Atari System 1)
#ifndef CYC_CPU
#define CYC_CPU 1
#endif




int main(int argc, char **argv)
{
    if (argc < 3) { fprintf(stderr, "usage: %s m68kops.c out.c\n", argv[0]); return 1; }
    // 1) names of the handlers, in table order, parsed from the source
    FILE *src = fopen(argv[1], "r");
    if (!src) { perror(argv[1]); return 1; }
    static char line[512];
    static char names[4096][64];
    int nn = 0, in_table = 0;
    while (fgets(line, sizeof line, src)) {
        if (strstr(line, "m68k_opcode_handler_table[] =")) { in_table = 1; continue; }
        if (!in_table) continue;
        char *p = strchr(line, '{');
        if (p && strncmp(p + 1, "m68k_op_", 8) == 0) {
            int k = 0; p++;
            while (*p && (isalnum((unsigned char)*p) || *p == '_') && k < 63) names[nn][k++] = *p++;
            names[nn][k] = 0;
            nn++;
        }
        if (strstr(line, "{0, 0, 0, {0, 0, 0}}")) break;
    }
    fclose(src);

    int nt = 0;
    while (m68k_opcode_handler_table[nt].mask != 0) nt++;
    if (nt != nn) { fprintf(stderr, "table mismatch: %d entries vs %d names\n", nt, nn); return 1; }

    // 2) build tables with Musashi's own builder
    m68ki_build_opcode_table();

    // 3) map handler pointers -> first table index (illegal = nt)
    static unsigned short idx[0x10000];
    for (int i = 0; i < 0x10000; i++) {
        void (*h)(void) = m68ki_instruction_jump_table[i];
        int found = nt;
        if (h != m68k_op_illegal)
            for (int k = 0; k < nt; k++) if (m68k_opcode_handler_table[k].opcode_handler == h) { found = k; break; }
        idx[i] = (unsigned short)found;
    }

    FILE *o = fopen(argv[2], "w");
    if (!o) { perror(argv[2]); return 1; }
    fprintf(o, "/* Auto-generated by tools/gen_m68k_tables.c - do not edit */\n");
    fprintf(o, "#include \"m68kcpu.h\"\n#include \"m68kops.h\"\n\n");
    fprintf(o, "void (*const m68k_handlers[%d])(void) = {\n", nt + 1);
    for (int k = 0; k < nt; k++) fprintf(o, "  %s,\n", names[k]);
    fprintf(o, "  m68k_op_illegal\n};\n\n");
    fprintf(o, "const uint16_t m68k_op_index_flash[0x10000] = {\n");
    for (int i = 0; i < 0x10000; i++) fprintf(o, "%u,%s", idx[i], (i % 16 == 15) ? "\n" : "");
    fprintf(o, "};\n\n");
    fprintf(o, "const unsigned char m68k_op_cycles[0x10000] = {\n");
    for (int i = 0; i < 0x10000; i++) fprintf(o, "%u,%s", m68ki_cycles[CYC_CPU][i], (i % 32 == 31) ? "\n" : "");
    fprintf(o, "};\n\n");
    fprintf(o, "/* Points to flash; the platform may copy it to RAM for speed. */\n");
    fprintf(o, "const uint16_t *m68k_op_index = m68k_op_index_flash;\n");
    fclose(o);
    fprintf(stderr, "OK: %d handlers -> %s\n", nt, argv[2]);
    return 0;
}
