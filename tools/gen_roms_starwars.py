"""Star Wars + The Empire Strikes Back ROMs -> main/drivers/arcades/starwars/rom_data.c
(the same layout as rom_load.c builds from storage). Run by tools/regen.sh starwars.

  tools/gen_roms_starwars.py roms/starwars roms/esb out.c

Each folder: MAME's files, or MAME's starwars.zip / esb.zip in it (or next to
it as <folder>.zip). A set that is not there is left to storage (NULL).
"""
