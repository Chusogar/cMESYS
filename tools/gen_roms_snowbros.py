#!/usr/bin/env python3
"""Pack the Snow Bros ROM set into main/drivers/arcades/snowbros/rom_data.c
(const arrays -> ESP32 flash). Run by tools/regen.sh snowbros.

Same loading as zxm/snowbros.c: sn6.bin = even lane, sn5.bin = odd lane,
sound ROM sbros-4.29 (or snowbros.4), graphics sbros-1.41 (single 512 KB file)
or ch0..ch3 (4 x 128 KB).
"""
import os, sys

def first(d, names):
    for n in names:
        p = os.path.join(d, n)
        if os.path.exists(p):
            return p
    sys.exit("missing ROM: " + " / ".join(names))

def main():
    d, out = sys.argv[1], sys.argv[2]
    even = open(first(d, ["sn6.bin"]), "rb").read()
    odd = open(first(d, ["sn5.bin"]), "rb").read()
    prog = bytearray(b"\xff" * 0x40000)
    for i, b in enumerate(even[:0x20000]): prog[i * 2] = b
    for i, b in enumerate(odd[:0x20000]): prog[i * 2 + 1] = b
    snd = bytearray(b"\x00" * 0x8000)
    s = open(first(d, ["snowbros.4", "sbros-4.29"]), "rb").read()
    snd[:len(s)] = s[:0x8000]
    gfx = bytearray(0x80000)
    single = os.path.join(d, "sbros-1.41")
    if os.path.exists(single):
        g = open(single, "rb").read()
        gfx[:len(g)] = g[:0x80000]
    else:
        for i in range(4):
            g = open(first(d, ["ch%d" % i, "ch%d.bin" % i]), "rb").read()
            gfx[i * 0x20000:i * 0x20000 + len(g)] = g[:0x20000]

    with open(out, "w") as f:
        f.write("// Auto-generated by tools/gen_roms.py - Snow Bros ROM data\n")
        f.write('#include "rom_data.h"\n\n')
        for name, data in (("sb_prog_rom", prog), ("sb_snd_rom", snd), ("sb_gfx_rom", gfx)):
            f.write("const uint8_t %s[%d] __attribute__((aligned(4))) = {\n" % (name, len(data)))
            for i in range(0, len(data), 32):
                f.write("".join("0x%02x," % b for b in data[i:i + 32]) + "\n")
            f.write("};\n\n")
    print("OK ->", out)

main()
