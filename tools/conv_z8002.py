#!/usr/bin/env python3
# Converts dsp-cpp's Z8002 (MAME z8000, C++) into C for cMESYS:
#   tools/conv_z8002.py <dsp-cpp> main/cpu/z8002  -> z8002_ops.inc, z8002_tab.c
import re, os
import sys
S = sys.argv[1] + "/src/cpu"   # dsp-cpp checkout
O = sys.argv[2]                # main/cpu/z8002
cpu_h = open(S + "/z8000/z8000cpu.h").read()
dab = open(S + "/z8000/z8000dab.h").read()
ops = open(S + "/z8000/z8000ops.hxx").read()
tbl = open(S + "/z8000/z8000tbl.hxx").read()

def cfuncs(src):
    # member definitions -> static C functions
    src = re.sub(r"^(\w[\w\s\*]*?)\s*z8002_device::(\w+)\(", lambda m: "static %s %s(" % (m.group(1).strip(), m.group(2)), src, flags=re.M)
    src = re.sub(r"int &(\w*space)", r"int \1", src)
    src = src.replace("\t", "    ")
    return src

ops = cfuncs(ops)
# prototypes for every static function (they call each other in any order)
protos = []
for m in re.finditer(r"^static ([\w\s\*]+?) (\w+)\(([^)]*)\)\s*\n\{", ops, flags=re.M):
    protos.append("static %s %s(%s);" % (m.group(1), m.group(2), m.group(3) or "void"))
tbl = tbl.replace("const z8002_device::Z8000_init z8002_device::table[] =", "static const z8000_init table[] =")
tbl = tbl.replace("&z8002_device::", "").replace("nullptr", "0")

out = []
out.append("""// z8002.c - Zilog Z8002 (unsegmented Z8000) for cMESYS: C port of dsp-cpp's
// cpu/z8002 (adapted from MAME src/devices/cpu/z8000; BSD-3-Clause,
// Juergen Buchmueller, Ernesto Corvi). Generated by tools/conv_z8002.py from
// the C++ sources, then kept by hand.
//
// The opcode functions work on the CPU being run (Z): z8002_run() sets it.
#include "z8002.h"
#include <string.h>

#ifdef ESP_PLATFORM
#include "esp_attr.h"
#endif

// Little-endian host overlay of the big-endian register file (as MAME).
#define BYTE8_XOR_BE(a) ((a) ^ 7)
#define BYTE4_XOR_BE(a) ((a) ^ 3)
#define BYTE_XOR_BE(a) ((a) ^ 1)
#define CLEAR_LINE 0
#define ASSERT_LINE 1
#define LOG(...) ((void)0)
#define logerror(...) ((void)0)
#define printf(...) ((void)0)
#define BIT(x, n) (((x) >> (n)) & 1)

static z8002 *Z;
#define m_op Z->op
#define m_ppc Z->ppc
#define m_pc Z->pc
#define m_psapseg Z->psapseg
#define m_psapoff Z->psapoff
#define m_fcw Z->fcw
#define m_refresh Z->refresh
#define m_nspseg Z->nspseg
#define m_nspoff Z->nspoff
#define m_irq_req Z->irq_req
#define m_irq_vec Z->irq_vec
#define m_op_valid Z->op_valid
#define m_regs Z->regs
#define m_nmi_state Z->nmi_state
#define m_irq_state Z->irq_state
#define m_mi Z->mi
#define m_halt Z->halt
#define m_icount Z->icount
#define m_vector_mult 1
#define m_program 0
#define m_data 0
#define m_stack 0
#define m_ns_out(x) ((void)0)
#define m_mo_out(x) ((void)0)

enum { Z8000_EPU = 0x80, Z8000_TRAP = 0x40, Z8000_NMI = 0x20, Z8000_SEGTRAP = 0x10,
       Z8000_NVI = 0x08, Z8000_VI = 0x04, Z8000_SYSCALL = 0x02, Z8000_RESET = 0x01 };
""")
out.append(cpu_h)
out.append(dab)
out.append("""
typedef struct { int beg, end, step, size, cycles; void (*opcode)(void); } z8000_init;
extern uint16_t z8002_exec_blk[0x1000], z8002_exec_ent[];    // z8002_tab.c (generated)
static uint8_t z8000_zsp[256];

#include "z8002_hot.h"           // what goes in RAM (tools/z8002_hot.py)
static inline int get_segmented_mode(void) { return 0; }
static inline uint32_t adjust_addr_for_nonseg_mode(uint32_t addr) { return addr; }
static uint32_t addr_add(uint32_t addr, uint32_t addend) { return (addr & 0xffff0000u) | ((addr + addend) & 0xffffu); }
static uint32_t addr_sub(uint32_t addr, uint32_t subtrahend) { return (addr & 0xffff0000u) | ((addr - subtrahend) & 0xffffu); }

static inline uint8_t RDMEM_B(int space, uint32_t addr) { (void)space; return Z->read(Z->user, (uint16_t)addr); }
static inline uint16_t RDMEM_W(int space, uint32_t addr)
{
    (void)space;
    addr &= ~1u;
    if (Z->read16) return Z->read16(Z->user, (uint16_t)addr);
    return (uint16_t)((Z->read(Z->user, (uint16_t)addr) << 8) | Z->read(Z->user, (uint16_t)(addr + 1)));
}
static uint32_t RDMEM_L(int space, uint32_t addr)
{
    addr &= ~1u;
    uint32_t r = (uint32_t)RDMEM_W(space, addr) << 16;
    return r + RDMEM_W(space, addr_add(addr, 2));
}
static inline void WRMEM_B(int space, uint32_t addr, uint8_t v) { (void)space; Z->write(Z->user, (uint16_t)addr, v); }
static inline void WRMEM_W(int space, uint32_t addr, uint16_t v)
{
    (void)space;
    addr &= ~1u;
    Z->write(Z->user, (uint16_t)addr, (uint8_t)(v >> 8));
    Z->write(Z->user, (uint16_t)(addr + 1), (uint8_t)v);
}
static void WRMEM_L(int space, uint32_t addr, uint32_t v)
{
    addr &= ~1u;
    WRMEM_W(space, addr, (uint16_t)(v >> 16));
    WRMEM_W(space, addr_add(addr, 2), (uint16_t)v);
}
static uint8_t RDPORT_B(int mode, uint16_t addr) { (void)mode; (void)addr; return 0xff; }
static uint16_t RDPORT_W(int mode, uint16_t addr) { (void)mode; (void)addr; return 0xffff; }
static void WRPORT_B(int mode, uint16_t addr, uint8_t v) { (void)mode; (void)addr; (void)v; }
static void WRPORT_W(int mode, uint16_t addr, uint16_t v) { (void)mode; (void)addr; (void)v; }
static void cycles(int n) { m_icount -= n; }

// program fetches straight from the ROM below fetch_end (z8002.h), else through read16
static inline uint16_t FETCH_W(uint32_t addr)
{
    addr &= 0xfffe;
    if (addr < Z->fetch_end) return (uint16_t)((Z->fetch[addr] << 8) | Z->fetch[addr + 1]);
    return RDMEM_W(0, addr);
}
static inline uint16_t RDOP(void) { uint16_t r = FETCH_W(m_pc); m_pc += 2; return r; }
static uint32_t get_operand(int opnum)
{
    if (!(m_op_valid & (1u << opnum))) {
        m_op[opnum] = FETCH_W(m_pc);
        m_pc += 2;
        m_op_valid |= (1u << opnum);
    }
    return m_op[opnum];
}
static uint32_t get_addr_operand(int opnum) { return get_operand(opnum); }
static uint32_t get_raw_addr_operand(int opnum) { return get_operand(opnum); }
""")
out.append("\n".join(protos) + "\n")
out.append("""
static void PUSH_PC(void);
static uint32_t GET_PC(uint32_t VEC) { return RDMEM_W(m_data, VEC + 2); }
static uint32_t get_reset_pc(void) { return RDMEM_W(m_program, 4); }
static uint16_t GET_FCW(uint32_t VEC) { return RDMEM_W(m_data, VEC); }
static uint32_t F_SEG_Z8001(void) { return 0; }
static uint32_t PSA_ADDR(void) { return m_psapoff; }
static uint32_t read_irq_vector(void) { return RDMEM_W(m_data, VEC00 + 2 * (m_irq_vec & 0xff)); }
""")
out.append(ops)
out.append("""
static void PUSH_PC(void) { PUSHW(SP, (uint16_t)m_pc); }
""")
out.append(tbl)
open(O + "/z8002_ops.inc", "w").write("\n".join(out))
# names of the table for the index generator
names = re.findall(r"\{\s*(0x[0-9a-f]+|0),\s*(0x[0-9a-f]+|0),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\w+)\s*\}", tbl)
print(len(protos), "functions,", len(names), "table entries")

# opcode -> table index (as init_tables(): later entries override earlier ones)
idx = [0] * 0x10000
for i, (b, e, st, sz, cy, fn) in enumerate(names):
    b, e, st = int(b, 0), int(e, 0), int(st)
    if st == 0:
        continue
    for v in range(b, e + 1, st):
        idx[v] = i
# Two levels (18 KB, small enough for RAM): 4096 block numbers by the top 12
# bits, blocks of 16 indices by the low 4 (the 64K table has 313 different).
blocks, blk = [], []
pos = {}
for i in range(0, 0x10000, 16):
    t = tuple(idx[i:i + 16])
    if t not in pos:
        pos[t] = len(blocks)
        blocks.append(t)
    blk.append(pos[t])
with open(O + "/z8002_tab.c", "w") as f:
    f.write("// z8002_tab.c - Z8002 opcode -> handler table index (generated by\n"
            "// tools/conv_z8002.py from z8000tbl). Two levels, in RAM (not const):\n"
            "// z8002_exec_ent[z8002_exec_blk[op >> 4] * 16 + (op & 15)].\n#include <stdint.h>\n\n")
    f.write("uint16_t z8002_exec_blk[0x1000] = {\n")
    for i in range(0, 0x1000, 16):
        f.write(",".join(str(x) for x in blk[i:i + 16]) + ",\n")
    f.write("};\n\nuint16_t z8002_exec_ent[%d * 16] = {\n" % len(blocks))
    for t in blocks:
        f.write(",".join(str(x) for x in t) + ",\n")
    f.write("};\n")
